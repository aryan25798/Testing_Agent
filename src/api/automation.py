"""
Automation Scripts Management API Endpoints.
"""

import io
import zipfile
from typing import List
from fastapi import APIRouter, Depends, HTTPException
from fastapi.responses import Response
from sqlalchemy.orm import Session
from src.database.session import get_db
from src.models.entities import AutomationScript, Project
from src.schemas.dtos import AutomationScriptRead

router = APIRouter(prefix="/automation", tags=["Automation"])


@router.get("/project/{project_id}", response_model=List[AutomationScriptRead])
def list_scripts_by_project(project_id: str, db: Session = Depends(get_db)):
    return db.query(AutomationScript).filter(AutomationScript.project_id == project_id).all()


@router.get("/project/{project_id}/download-zip")
def download_automation_zip(project_id: str, db: Session = Depends(get_db)):
    project = db.query(Project).filter(Project.id == project_id).first()
    if not project:
        raise HTTPException(status_code=404, detail="Project not found")

    scripts = db.query(AutomationScript).filter(AutomationScript.project_id == project_id).all()
    if not scripts:
        raise HTTPException(status_code=400, detail="No automation scripts found for this project.")

    zip_buffer = io.BytesIO()
    with zipfile.ZipFile(zip_buffer, "w", zipfile.ZIP_DEFLATED) as zip_file:
        # Add README
        readme_content = f"# Automation Test Suite for {project.name}\nFramework: {project.framework}\nGenerated by Testing Agent Platform\n"
        zip_file.writestr("README.md", readme_content)

        # Add all scripts
        for s in scripts:
            clean_path = s.file_path if s.file_path else f"tests/{s.script_name}.py"
            zip_file.writestr(clean_path, s.code_content)

    zip_buffer.seek(0)
    filename = f"{project.name.replace(' ', '_')}_automation_suite.zip"
    return Response(
        content=zip_buffer.getvalue(),
        media_type="application/zip",
        headers={"Content-Disposition": f"attachment; filename={filename}"}
    )
